describe('classifyItem', () => {
  it('reads at least 80 real lines', () => {
    expect(TABLE.length).toBeGreaterThanOrEqual(80)
  })

  it.each(TABLE)('%s → %s', (name, expected) => {
    expect(classifyItem(name)).toBe(expected)
  })

  it('ignores case, spacing and punctuation', () => {
    expect(classifyItem('  butter   CHICKEN!! ')).toBe('nonveg')
    expect(classifyItem('KINGFISHER-ULTRA')).toBe('alcohol')
    expect(classifyItem('virgin—mojito')).toBeNull()
  })

  it('matches whole words only', () => {
    expect(classifyItem('Ginger chai')).toBeNull() // gin
    expect(classifyItem('Shami Paratha')).toBe('nonveg') // shami is meat; "ham" inside it is not what matched
    expect(classifyItem('Champagne')).toBe('alcohol') // "ham" inside it isn't meat
    expect(classifyItem('Buffet lunch')).toBeNull() // buff
    expect(classifyItem('Kingfish curry')).toBe('nonveg') // the fish, not the beer
    expect(classifyItem('Rosebud cake')).toBeNull() // bud
  })
})
